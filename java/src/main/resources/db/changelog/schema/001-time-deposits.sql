--comment: README table "timeDeposits", mapped to snake_case because PostgreSQL folds unquoted identifiers to lower case.
CREATE TABLE time_deposits (
    id        INTEGER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_type VARCHAR(50)    NOT NULL,
    days      INTEGER        NOT NULL,
    balance   NUMERIC(19, 2) NOT NULL,
    -- Optimistic locking (JPA @Version). The balance update holds a pessimistic row lock; this column makes any
    -- other writer fail on a stale read instead of silently overwriting a newer balance (lost update).
    version   BIGINT         NOT NULL DEFAULT 0,

    CONSTRAINT chk_time_deposits_days_non_negative CHECK (days >= 0)
    -- Deliberately no CHECK on balance >= 0: the legacy calculator accepts negative balances, so that would be a new
    -- business rule. And none on plan_type: unknown plans must stay storable (they earn no interest), and new plans
    -- must be addable without a schema change.
);
