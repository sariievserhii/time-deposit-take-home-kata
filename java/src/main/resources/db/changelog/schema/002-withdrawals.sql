--comment: README table "withdrawals". History of withdrawals per deposit (see README, "Assumptions").
CREATE TABLE withdrawals (
    id              INTEGER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time_deposit_id INTEGER        NOT NULL REFERENCES time_deposits (id),
    amount          NUMERIC(19, 2) NOT NULL,
    date            DATE           NOT NULL,

    CONSTRAINT chk_withdrawals_amount_positive CHECK (amount > 0)
);

-- GET loads withdrawals by deposit (LEFT JOIN on time_deposit_id).
CREATE INDEX idx_withdrawals_time_deposit_id ON withdrawals (time_deposit_id);
--rollback DROP TABLE withdrawals;
